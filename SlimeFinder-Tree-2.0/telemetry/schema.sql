-- SlimeFinder 匿名统计 D1 schema（v1）
CREATE TABLE IF NOT EXISTS telemetry (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  received_at TEXT NOT NULL,
  event TEXT NOT NULL,
  app_version TEXT,
  channel TEXT,
  language TEXT,
  platform TEXT,
  os_name TEXT,
  os_arch TEXT,
  cpu TEXT,
  cpu_threads INTEGER,
  ram_gb INTEGER,
  gpu TEXT,
  gpu_available INTEGER,
  edition TEXT,
  mode TEXT,
  algorithm TEXT,
  ring_scan TEXT,
  seed TEXT,
  range_log10 INTEGER,
  range_x INTEGER,
  range_z INTEGER,
  duration_ms INTEGER,
  scan_ms INTEGER,
  match_ms INTEGER,
  scanned_chunks INTEGER,
  chunks_per_sec REAL,
  result_count INTEGER,
  total_found INTEGER,
  best_value REAL,
  best_x INTEGER,
  best_z INTEGER,
  cancelled INTEGER,
  stopped_early INTEGER,
  gpu_used INTEGER,
  settings_json TEXT,
  results_json TEXT,
  payload TEXT
);
CREATE INDEX IF NOT EXISTS idx_telemetry_event_time ON telemetry(event, received_at);
CREATE INDEX IF NOT EXISTS idx_telemetry_version ON telemetry(app_version);
CREATE INDEX IF NOT EXISTS idx_telemetry_platform ON telemetry(platform, edition);
